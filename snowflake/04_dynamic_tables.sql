-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT line.ID AS ENTITY_ID, line.NAME AS ENTITY_NAME,
       line.REGION, line.CATEGORY, line.RISK_TIER, line.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.UNITS_SOLD) AS UNITS_SOLD,
       SUM(observation.NET_SALES_SGD) AS NET_SALES_SGD,
       SUM(observation.EXCEPTION_COUNT) AS EXCEPTION_COUNT,
       SUM(observation.MARKDOWN_COUNT) AS MARKDOWN_COUNT,
       SUM(observation.PROMO_DELAY) AS PROMO_DELAY_COUNT,
       SUM(observation.PRICE_AUDIT_DUE) AS PRICE_AUDIT_DUE,
       SUM(observation.PRICE_AUDIT_DONE) AS PRICE_AUDIT_DONE,
       100.0 * (SUM(observation.UNITS_SOLD) - SUM(observation.EXCEPTION_COUNT)) / NULLIF(SUM(observation.UNITS_SOLD), 0) AS CLEAN_PRICE_PCT,
       100.0 * SUM(observation.MARKDOWN_COUNT) / NULLIF(SUM(observation.EXCEPTION_COUNT), 0) AS EXCEPTION_MARKDOWN_PCT,
       100.0 * SUM(observation.PRICE_AUDIT_DONE) / NULLIF(SUM(observation.PRICE_AUDIT_DUE), 0) AS PRICE_AUDIT_PCT,
       AVG(observation.MARKDOWN_DEPTH_PCT) AS AVG_MARKDOWN_DEPTH_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.LINE_DAILY observation
JOIN RAW.MERCH_LINES line ON line.ID = observation.ENTITY_ID
GROUP BY line.ID, line.NAME, line.REGION, line.CATEGORY, line.RISK_TIER, line.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(UNITS_SOLD) AS UNITS_SOLD, SUM(NET_SALES_SGD) AS NET_SALES_SGD,
       SUM(EXCEPTION_COUNT) AS EXCEPTION_COUNT, SUM(MARKDOWN_COUNT) AS MARKDOWN_COUNT,
       100.0 * SUM(MARKDOWN_COUNT) / NULLIF(SUM(EXCEPTION_COUNT), 0) AS EXCEPTION_MARKDOWN_PCT
FROM RAW.LINE_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.EXCEPTION_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EXCEPTION_TYPE, SUM(EXCEPTION_COUNT) AS EXCEPTION_COUNT,
       SUM(MARKDOWN_COUNT) AS MARKDOWN_COUNT,
       SUM(PROMO_DELAY) AS PROMO_DELAY_COUNT,
       SUM(NET_SALES_SGD) AS EXPOSED_SALES_SGD,
       100.0 * SUM(MARKDOWN_COUNT) / NULLIF(SUM(EXCEPTION_COUNT), 0) AS EXCEPTION_MARKDOWN_PCT
FROM RAW.LINE_DAILY
WHERE EXCEPTION_COUNT > 0
GROUP BY EXCEPTION_TYPE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(UNITS_SOLD) AS UNITS, SUM(EXCEPTION_COUNT) AS EXCEPTIONS,
         SUM(MARKDOWN_COUNT) AS MARKDOWNS, SUM(PROMO_DELAY) AS DELAYS, SUM(NET_SALES_SGD) AS NET_SALES_SGD,
         SUM(PRICE_AUDIT_DUE) AS PRICE_AUDIT_DUE, SUM(PRICE_AUDIT_DONE) AS PRICE_AUDIT_DONE,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.LINE_DAILY
), book AS (SELECT COUNT(*) AS LINE_COUNT FROM RAW.MERCH_LINES),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.FUNDING_AGREEMENTS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Price Integrity Rate' AS TITLE,
         100.0 * (UNITS - EXCEPTIONS) / NULLIF(UNITS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Pricing Exceptions Raised', EXCEPTIONS, '' FROM observations
  UNION ALL SELECT 3, 'Unplanned Markdowns', MARKDOWNS, '' FROM observations
  UNION ALL SELECT 4, 'Exception Markdown Rate', 100.0 * MARKDOWNS / NULLIF(EXCEPTIONS, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Promo Setup Delays', DELAYS, '' FROM observations
  UNION ALL SELECT 6, 'Net Sales (SGD K)', NET_SALES_SGD / 1e3, '' FROM observations
  UNION ALL SELECT 7, 'Units Sold', UNITS, '' FROM observations
  UNION ALL SELECT 8, 'Price Audit Compliance', 100.0 * PRICE_AUDIT_DONE / NULLIF(PRICE_AUDIT_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Merchandise Lines Monitored', LINE_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Funding Agreement Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Funding Agreements Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.EXCEPTION_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
