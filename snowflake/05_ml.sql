-- Unplanned-markdown risk scoring and pricing-exception forecast over the synthetic snapshot.
-- Predicts P(unplanned markdown for the line in the next 7 days) per line and
-- reports out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.MARKDOWN_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, a.CATEGORY, a.RISK_TIER, a.RANGE_AGE_YEARS,
       r.MARKDOWN_DEPTH_PCT, r.PRICE_CHANGE_LEAD_HRS,
       AVG(r.MARKDOWN_DEPTH_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS MARKDOWN_DEPTH_7D,
       SUM(r.MARKDOWN_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS MARKDOWNS_30D,
       IFF(SUM(r.MARKDOWN_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'MARKDOWN', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.LINE_DAILY r JOIN RAW.MERCH_LINES a ON a.ID = r.ENTITY_ID
-- Town-wide competitor price campaigns are not line-driven, so they are excluded from training.
WHERE r.EXCEPTION_TYPE <> 'Competitor price campaign';

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.MARKDOWN_TRAIN AS
SELECT CATEGORY, RISK_TIER, RANGE_AGE_YEARS, MARKDOWN_DEPTH_PCT, PRICE_CHANGE_LEAD_HRS, MARKDOWN_DEPTH_7D, MARKDOWNS_30D, LABEL
FROM ML.MARKDOWN_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.MARKDOWN_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, RISK_TIER, RANGE_AGE_YEARS, MARKDOWN_DEPTH_PCT, PRICE_CHANGE_LEAD_HRS, MARKDOWN_DEPTH_7D, MARKDOWNS_30D, LABEL
FROM ML.MARKDOWN_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.MARKDOWN_RISK_MODEL(
  INPUT_DATA => TABLE(ML.MARKDOWN_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.MARKDOWN_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.MARKDOWN_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'RANGE_AGE_YEARS', RANGE_AGE_YEARS,
           'MARKDOWN_DEPTH_PCT', MARKDOWN_DEPTH_PCT, 'PRICE_CHANGE_LEAD_HRS', PRICE_CHANGE_LEAD_HRS,
           'MARKDOWN_DEPTH_7D', MARKDOWN_DEPTH_7D, 'MARKDOWNS_30D', MARKDOWNS_30D)):probability:MARKDOWN::FLOAT AS P
  FROM ML.MARKDOWN_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'MARKDOWN', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'MARKDOWN', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'MARKDOWN', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'MARKDOWN', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per line (label unknown, so excluded from features).
CREATE TABLE ML.MARKDOWN_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.MARKDOWN_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.MARKDOWN_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'RANGE_AGE_YEARS', RANGE_AGE_YEARS,
           'MARKDOWN_DEPTH_PCT', MARKDOWN_DEPTH_PCT, 'PRICE_CHANGE_LEAD_HRS', PRICE_CHANGE_LEAD_HRS,
           'MARKDOWN_DEPTH_7D', MARKDOWN_DEPTH_7D, 'MARKDOWNS_30D', MARKDOWNS_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:MARKDOWN::FLOAT, 4) AS MARKDOWN_PROB_7D,
       CASE WHEN P:probability:MARKDOWN::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:MARKDOWN::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Network-wide pricing-exception forecast (14 days) from the daily series, for pricing desk staffing.
CREATE VIEW ML.DAILY_EXCEPTIONS AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(EXCEPTION_COUNT)::FLOAT AS EXCEPTION_COUNT
FROM RAW.LINE_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.EXCEPTION_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_EXCEPTIONS),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'EXCEPTION_COUNT'
);

CREATE TABLE ML.EXCEPTION_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS EXCEPTION_COUNT,
       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.EXCEPTION_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
